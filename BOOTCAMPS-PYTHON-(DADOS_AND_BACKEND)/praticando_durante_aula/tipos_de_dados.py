# Tipos de dados em Python

print( 1 + 10) # Inteiro (int)
print(3.14 * 2) # Ponto flutuante (float)
print("Olá, " + "mundo!") # String (str)
print(True and False) # Booleano (bool)
print([1, 2, 3] + [4, 5, 6]) # Lista (list)
print((1, 2, 3) + (4, 5, 6)) # Tupla (tuple)
print({"nome": "Alice", "idade": 30}) # Dicionário (dict)
print({1, 2, 3} | {3, 4, 5}) # Conjunto (set)

# Tipos de dados especiais
print(None) # NoneType  
print(b'bytes de exemplo') # Bytes (bytes)
print(bytearray(b'bytearray de exemplo')) # Bytearray (bytearray)
print(range(5)) # Range (range)
print(complex(2, 3)) # Número complexo (complex)
